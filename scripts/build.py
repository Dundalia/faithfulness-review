"""Regenerate every view from papers/ and tags.yaml:
index.csv, tags.csv, relations.csv, index.md, corpus.txt and site/data.json (the dashboard's data)."""
import csv, datetime, json, re
from records import MAP, all_records, sections


def vocabulary():
    """Namespaces from tags.yaml, with their comment as description and each value's definition."""
    out, cur = [], None
    for line in (MAP / "tags.yaml").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        m = re.match(r"^([a-z-]+):\s*(free)?\s*(?:#\s*(.*))?$", line)
        if m:
            cur = {"name": m.group(1), "free": bool(m.group(2)), "description": (m.group(3) or "").strip(), "values": []}
            out.append(cur)
            continue
        m = re.match(r"^\s+([a-z0-9.-]+):\s*(.*)$", line)
        if m and cur:
            cur["values"].append({"value": m.group(1), "definition": m.group(2).strip()})
    return out


def venue_type(v):
    v = (v or "preprint").lower()
    if v.startswith("withdrawn"):
        return "withdrawn"
    if v.startswith("model card"):
        return "model-card"
    if v in ("preprint", "blog"):
        return v
    return "workshop" if "workshop" in v else "venue"


def relations(body):
    out = []
    for line in sections(body)["relations"]:
        m = re.match(r"(\S+) \[\[([^\]]+)\]\]:?\s*(.*)", line)
        if m:
            out.append({"verb": m.group(1), "target": m.group(2), "note": m.group(3)})
    return out


def definitions():
    """definitions.csv and the clusters in runs/D_definitions/synth_<family>.json (built by definitions.py)."""
    path = MAP / "definitions.csv"
    if not path.exists():
        return [], []
    with open(path, newline="") as f:
        defs = [{k: r[k] for k in ("id", "key", "family", "term", "kind", "stance", "source", "where", "quote", "gloss", "cluster")}
                for r in csv.DictReader(f)]
    clusters = []
    for fam in ("faithfulness", "counterfactual", "monitorability"):
        synth = MAP / "runs" / "D_definitions" / f"synth_{fam}.json"
        if synth.exists():
            clusters += [{"family": fam, **{k: c[k] for k in ("id", "name", "description")}}
                         for c in json.loads(synth.read_text())["clusters"]]
    return defs, clusters


def main():
    recs = all_records()
    rows = []
    for r in recs:
        s = sections(r["body"])
        rows.append({**{k: r.get(k) for k in ("key", "title", "authors", "year", "venue", "url", "checked")},
                     "tags": "; ".join(r.get("tags") or []), **{k: s[k] for k in ("tldr", "problem", "method", "findings", "limits")},
                     "relations": " | ".join(s["relations"])})
    with open(MAP / "index.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader(); w.writerows(rows)
    with open(MAP / "tags.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["key", "namespace", "value"])
        for r in recs:
            for t in r.get("tags") or []:
                ns, _, val = t.partition(":")
                w.writerow([r["key"], ns, val])
    with open(MAP / "relations.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["key", "verb", "target", "note"])
        for r in recs:
            for x in relations(r["body"]):
                w.writerow([r["key"], x["verb"], x["target"], x["note"]])
    (MAP / "corpus.txt").write_text("".join(f"{r['key']}: {r['title']} ({r['year']})\n" for r in recs))

    md = ["# Literature Map Index", "", f"{len(recs)} papers, newest first. Generated by `scripts/build.py` from `papers/`; do not edit by hand.", "",
          "| Key | Year | Venue | Title | Tags | TL;DR |", "| --- | --- | --- | --- | --- | --- |"]
    for row, r in sorted(zip(rows, recs), key=lambda x: (-(x[0]["year"] or 0), x[0]["key"])):
        tags = ", ".join(t for t in (r.get("tags") or []) if not t.startswith(("model:", "metric:", "source:")))
        md.append(f"| [{row['key']}](papers/{row['key']}.md) | {row['year']} | {row['venue']} | [{row['title']}]({row['url']}) | {tags} | {row['tldr'] or row['findings']} |")
    (MAP / "index.md").write_text("\n".join(md) + "\n")

    papers = []
    for r in recs:
        s = sections(r["body"])
        papers.append({**{k: r.get(k) for k in ("key", "title", "authors", "year", "venue", "url", "checked")},
                       "venue_type": venue_type(r.get("venue")), "tags": r.get("tags") or [],
                       **{k: s[k] for k in ("tldr", "problem", "method", "findings", "limits")},
                       "relations": relations(r["body"]),
                       "new_tags": [dict(zip(("tag", "definition"), (l.split(": ", 1) + [""])[:2])) for l in s["new_tags"]]})
    (MAP / "site").mkdir(exist_ok=True)
    defs, clusters = definitions()
    data = {"generated": datetime.date.today().isoformat(), "namespaces": vocabulary(), "papers": papers,
            "definitions": defs, "clusters": clusters}
    (MAP / "site" / "data.json").write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")))
    print(f"built views and site/data.json for {len(recs)} papers and {len(defs)} definitions")


main()
